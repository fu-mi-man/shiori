import { describe, expect, it } from "vitest";
import { addDays } from "./add-days";

describe("addDays", () => {
  it.each([
    ["通常の日付", "2025-08-01", 1, "2025-08-02"],
    ["0日加算", "2025-08-01", 0, "2025-08-01"],
    ["月末（1月→2月）", "2025-01-31", 1, "2025-02-01"],
    ["年末（12月→1月）", "2025-12-31", 1, "2026-01-01"],
    ["うるう年の2/28", "2024-02-28", 1, "2024-02-29"],
    ["うるう年の2/29", "2024-02-29", 1, "2024-03-01"],
    ["非うるう年の2/28", "2025-02-28", 1, "2025-03-01"],
    ["9日加算", "2025-01-01", 9, "2025-01-10"],
  ])("%s", (_, startDate, days, expected) => {
    expect(addDays(startDate, days)).toBe(expected);
  });
});
